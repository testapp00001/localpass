/*
 * Prints the real x64 layout of every WebAuthn plugin API struct that crates/lp-winauth mirrors, as the
 * Rust test code that pins it. The output is checked in as crates/lp-winauth/src/sys/layout_tests.rs
 * (everything below the "generated" line), so a header or struct change is caught by `cargo test`.
 *
 * Source of truth: the Windows SDK headers, compiled as C (REFCLSID/REFGUID are pointers there), x64.
 * In C++ mode those two would be references and the offsets would still match, but C is what the
 * notes' tables describe.
 *
 * Regenerate (save these lines as a .bat and run it from the repo root; adjust the Visual Studio path;
 * the SDK version in /I is optional because vcvars64 already points at the installed SDK):
 *
 *   @echo off
 *   call "C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvars64.bat"
 *   cl /nologo /TC /W3 /I"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\um" ^
 *      crates\lp-winauth\tools\layout_check.c /Fe:%TEMP%\lp_layout.exe /Fo:%TEMP%\
 *   %TEMP%\lp_layout.exe > %TEMP%\layout_generated.rs
 *
 * then replace the test functions inside `mod generated` of src/sys/layout_tests.rs (between the
 * "BEGIN GENERATED" and "END GENERATED" markers) with layout_generated.rs minus its two leading // lines,
 * indented four spaces. Only the checked-in numbers matter at test time; cargo never builds this file.
 * Header version used for the checked-in numbers: Windows SDK 10.0.26100.0.
 *
 * Only the FINAL plugin API is covered. The EXPERIMENTAL_* generation (webauthn.h 1402-1936,
 * pluginauthenticator.h EXPERIMENTAL_*) is deliberately absent.
 */
